# -*- coding: utf-8 -*-
"""
export_hls_weights.py — Extract + BatchNorm-fold real trained weights from
the EMA-Det "final" checkpoint into a C++ header, and dump reference
input/output pairs for validating the HLS C++ translation.

Scope: Block1 -> pool1 -> Block2 -> pool2 -> Gate1, and continuing through
Block3 -> pool3 -> Block4 -> pool4 -> Gate2. This covers both early-exit
gates end-to-end with real weights (not synthetic placeholders).

IMPORTANT — this environment has no C/C++ compiler and no Vivado/Vitis HLS
installation (verified: g++/clang++/cl/gcc all absent). The generated C++
in hardware/hls/ has NOT been compiled, simulated, or synthesized. Do not
report LUT/BRAM/latency/power numbers from it until it has actually been
built and run on a machine with the toolchain — this script's job is only
to make that validation possible (reference_io.json + weights.h), not to
perform it.
"""
import json
import os

import cv2
import numpy as np
import torch

from ema_det import EMADet

CKPT = r"C:\Users\enesm\Desktop\emadet\emadetforspringer\results\emadet_final_best.pt"
OUT_DIR = r"C:\Users\enesm\Desktop\emadet\emadetforspringer\hardware\hls"
TEST_DIR = r"C:\Users\enesm\Desktop\emadet\emadetforspringer\data\shuffled_dataset_detect_clean\test"


def fold_bn(conv_w: torch.Tensor, bn: torch.nn.BatchNorm2d):
    """Fold BatchNorm2d into the preceding conv's weight/bias.
    y = gamma * (conv(x) - mean) / sqrt(var+eps) + beta
      = (gamma/sqrt(var+eps)) * conv(x) + (beta - gamma*mean/sqrt(var+eps))
    conv_w has no bias (bias=False everywhere in ema_det.py), so the folded
    bias is exactly the additive term above.
    """
    gamma = bn.weight.detach()
    beta = bn.bias.detach()
    mean = bn.running_mean.detach()
    var = bn.running_var.detach()
    eps = bn.eps
    scale = gamma / torch.sqrt(var + eps)
    folded_w = conv_w.detach() * scale.view(-1, 1, 1, 1)
    folded_b = beta - mean * scale
    return folded_w.numpy(), folded_b.numpy()


def fold_conv_bn_seq(seq: torch.nn.Sequential, idx_conv: int, idx_bn: int):
    conv = seq[idx_conv]
    bn = seq[idx_bn]
    return fold_bn(conv.weight, bn)


def array_to_cpp(name: str, arr: np.ndarray, dtype="float") -> str:
    flat = arr.flatten()
    dims = "".join(f"[{d}]" for d in arr.shape)
    values = ", ".join(f"{v:.8e}f" for v in flat)
    return f"static const {dtype} {name}{dims} = {{ {values} }};\n"


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    model = EMADet(use_attention=False)
    model.load_state_dict(torch.load(CKPT, map_location="cpu"))
    model.eval()

    header_parts = [
        "// AUTO-GENERATED by export_hls_weights.py — real trained weights from",
        f"// {os.path.basename(CKPT)} (EMA-Det final config, BatchNorm folded into conv).",
        "// NOT compiled or synthesized in this environment — see hardware/hls/README.md.",
        "#pragma once\n",
    ]

    # Block1: Laplacian/Sobel-initialized conv, 1->16, BN folded. No bias in
    # nn.Conv2d itself, but BN fold introduces one.
    w, b = fold_bn(model.block1.conv.weight, model.block1.bn)
    header_parts.append(array_to_cpp("BLOCK1_W", w))   # (16,1,3,3)
    header_parts.append(array_to_cpp("BLOCK1_B", b))   # (16,)

    # Block2: conv_block(16,32) = [Conv,BN,LReLU, Conv,BN,LReLU]
    w, b = fold_conv_bn_seq(model.block2, 0, 1)
    header_parts.append(array_to_cpp("BLOCK2A_W", w)); header_parts.append(array_to_cpp("BLOCK2A_B", b))
    w, b = fold_conv_bn_seq(model.block2, 3, 4)
    header_parts.append(array_to_cpp("BLOCK2B_W", w)); header_parts.append(array_to_cpp("BLOCK2B_B", b))

    # Gate1: conv1x1(32->16) + BN + ReLU, then FC(16->1) after GAP
    w, b = fold_bn(model.gate1.conv.weight, model.gate1.bn)
    header_parts.append(array_to_cpp("GATE1_CONV_W", w)); header_parts.append(array_to_cpp("GATE1_CONV_B", b))
    header_parts.append(array_to_cpp("GATE1_FC_W", model.gate1.head.weight.detach().numpy()))
    header_parts.append(array_to_cpp("GATE1_FC_B", model.gate1.head.bias.detach().numpy()))

    # Block3: conv_block(32,64)
    w, b = fold_conv_bn_seq(model.block3, 0, 1)
    header_parts.append(array_to_cpp("BLOCK3A_W", w)); header_parts.append(array_to_cpp("BLOCK3A_B", b))
    w, b = fold_conv_bn_seq(model.block3, 3, 4)
    header_parts.append(array_to_cpp("BLOCK3B_W", w)); header_parts.append(array_to_cpp("BLOCK3B_B", b))

    # Block4: conv_block(64,128)
    w, b = fold_conv_bn_seq(model.block4, 0, 1)
    header_parts.append(array_to_cpp("BLOCK4A_W", w)); header_parts.append(array_to_cpp("BLOCK4A_B", b))
    w, b = fold_conv_bn_seq(model.block4, 3, 4)
    header_parts.append(array_to_cpp("BLOCK4B_W", w)); header_parts.append(array_to_cpp("BLOCK4B_B", b))

    # Gate2: conv1x1(128->64) + BN + ReLU, then FC(64->1) after GAP
    w, b = fold_bn(model.gate2.conv.weight, model.gate2.bn)
    header_parts.append(array_to_cpp("GATE2_CONV_W", w)); header_parts.append(array_to_cpp("GATE2_CONV_B", b))
    header_parts.append(array_to_cpp("GATE2_FC_W", model.gate2.head.weight.detach().numpy()))
    header_parts.append(array_to_cpp("GATE2_FC_B", model.gate2.head.bias.detach().numpy()))

    with open(os.path.join(OUT_DIR, "weights.h"), "w") as f:
        f.write("\n".join(header_parts))
    print(f"Wrote weights.h ({sum(len(p) for p in header_parts)} bytes)")

    # --- Reference I/O for validating the C++ translation later ---
    test_imgs = sorted(
        [f for f in os.listdir(os.path.join(TEST_DIR, "images")) if f.endswith(".jpg")]
    )[:8]

    ref = []
    for fname in test_imgs:
        path = os.path.join(TEST_DIR, "images", fname)
        img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
        img = cv2.resize(img, (128, 128)).astype(np.float32) / 255.0

        bin_path = os.path.join(OUT_DIR, f"input_{fname.replace('.jpg', '.bin')}")
        img.tofile(bin_path)  # raw float32, row-major, 128*128 values

        x = torch.tensor(img).unsqueeze(0).unsqueeze(0)
        with torch.no_grad():
            f_ = model.pool1(model.block1(x))
            f_ = model.pool2(model.block2(f_))
            gate1_logit = model.gate1(f_).item()
            f_ = model.pool3(model.block3(f_))
            f_ = model.pool4(model.block4(f_))
            gate2_logit = model.gate2(f_).item()

        ref.append({"input_bin": os.path.basename(bin_path),
                     "gate1_logit": gate1_logit, "gate2_logit": gate2_logit})

    with open(os.path.join(OUT_DIR, "reference_io.json"), "w") as f:
        json.dump(ref, f, indent=2)

    # Plain CSV too, so the C++ testbench doesn't need a JSON parser.
    with open(os.path.join(OUT_DIR, "reference_io.csv"), "w") as f:
        f.write("input_bin,gate1_logit,gate2_logit\n")
        for r in ref:
            f.write(f"{r['input_bin']},{r['gate1_logit']:.8f},{r['gate2_logit']:.8f}\n")

    print(f"Wrote reference_io.json / reference_io.csv ({len(ref)} test samples) for later C++ validation")

    # --- Block1-only golden reference (for validating a standalone streaming
    # Block1 kernel, independent of the rest of the network) ---
    block1_dir = os.path.join(OUT_DIR, "block1_ref")
    os.makedirs(block1_dir, exist_ok=True)
    for fname in test_imgs[:2]:
        path = os.path.join(TEST_DIR, "images", fname)
        img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
        img = cv2.resize(img, (128, 128)).astype(np.float32) / 255.0
        x = torch.tensor(img).unsqueeze(0).unsqueeze(0)
        with torch.no_grad():
            block1_out = model.block1(x)[0].numpy()  # (16, 128, 128), post-LeakyReLU
        stem = fname.replace(".jpg", "")
        img.tofile(os.path.join(block1_dir, f"{stem}_input.bin"))          # 128*128 float32
        block1_out.tofile(os.path.join(block1_dir, f"{stem}_block1_out.bin"))  # 16*128*128 float32
    print(f"Wrote Block1-only golden reference (input + post-LeakyReLU output) -> {block1_dir}")


if __name__ == "__main__":
    main()
